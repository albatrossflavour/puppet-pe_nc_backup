# frozen_string_literal: true

require 'spec_helper'
require 'open3'
require 'tmpdir'

# Runs the exec that removes the old cron job in systemd mode against a fake
# crontab command, to show it removes only our job and does nothing on a host
# without cron.
describe 'pe_nc_backup', type: :class do
  let(:facts) { on_supported_os.values.first }
  let(:params) { { schedule_type: 'systemd' } }
  let(:tmp) { Dir.mktmpdir('pe_nc_backup_cron') }
  let(:crontab_file) { File.join(tmp, 'crontab.txt') }
  let(:exec) { catalogue.resource('Exec', 'pe_nc_backup remove cron job') }

  # What Puppet's cron type writes for the 2.x and earlier releases, between other jobs.
  let(:existing) do
    <<~CRON
      # HEADER: This file was autogenerated at 2025-01-01 by puppet.
      MAILTO=root
      0 1 * * * /usr/local/bin/something-else
      # Puppet Name: pe_nc_backup
      */5 * * * * /opt/pe_nc_backup/bin/pe_nc_backup /opt/pe_nc_backup
      # Puppet Name: other
      0 2 * * * /usr/local/bin/other
    CRON
  end

  after(:each) { FileUtils.rm_rf(tmp) }

  # A crontab that reads and writes one file, as `crontab -u user -l` and `crontab -u user -` would.
  def install_fake_crontab
    bindir = File.join(tmp, 'bin')
    FileUtils.mkdir_p(bindir)
    File.write(File.join(bindir, 'crontab'), <<~SH)
      #!/bin/sh
      [ "$1" = "-u" ] && [ "$2" = "pe-puppet" ] || exit 2
      case "$3" in
        -l) [ -f '#{crontab_file}' ] || { echo "no crontab for $2" >&2; exit 1; }; cat '#{crontab_file}' ;;
        -) cat > '#{crontab_file}' ;;
        *) exit 2 ;;
      esac
    SH
    File.chmod(0o755, File.join(bindir, 'crontab'))
    bindir
  end

  def sh(command, path)
    Open3.capture2e({ 'PATH' => path }, '/bin/sh', '-c', command)[1].success?
  end

  def system_path(*dirs)
    (dirs + ['/usr/bin', '/bin']).join(':')
  end

  it 'removes only the pe_nc_backup job, then has nothing left to do' do
    File.write(crontab_file, existing)
    path = system_path(install_fake_crontab)
    expect(sh(exec[:onlyif], path)).to be(true)
    expect(sh(exec[:command], path)).to be(true)
    expect(File.read(crontab_file)).to eq(existing.lines.reject { |l| l.include?('pe_nc_backup') }.join)
    expect(sh(exec[:onlyif], path)).to be(false)
  end

  it 'does nothing when the user has no crontab' do
    expect(sh(exec[:onlyif], system_path(install_fake_crontab))).to be(false)
    expect(File.exist?(crontab_file)).to be(false)
  end

  it 'does nothing on a host without cron installed' do
    # Only a directory with sh, grep and awk in it, and no crontab anywhere.
    bindir = File.join(tmp, 'nocron')
    FileUtils.mkdir_p(bindir)
    ['grep', 'awk', 'printf'].each do |tool|
      found = ['/usr/bin', '/bin'].map { |d| File.join(d, tool) }.find { |f| File.executable?(f) }
      File.symlink(found, File.join(bindir, tool)) if found
    end
    expect(sh(exec[:onlyif], bindir)).to be(false)
  end

  it 'leaves the crontab untouched if reading it fails' do
    File.write(crontab_file, existing)
    path = system_path(install_fake_crontab)
    File.chmod(0o000, crontab_file)
    skip 'running as root, the file stays readable' if Process.uid.zero?
    expect(sh(exec[:command], path)).to be(false)
    File.chmod(0o644, crontab_file)
    expect(File.read(crontab_file)).to eq(existing)
  end
end
